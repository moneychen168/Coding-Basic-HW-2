#!/usr/bin/env python3
"""scripts/final/aggregate.py -- report tables from one final-matrix run (owner: agent-A).

Usage:  python3 -I scripts/final/aggregate.py results/final_<jobid> [-o tables.md] [--phi 0.5]
Pure stdlib; runs on the login node (reads CSV/log files only, never touches the GPU).

Every number in tables.md is read from a file in the run directory or computed from such numbers
(ratios, geometric means, max/min/sum); nothing is typed in by hand. Each table names its source.
Inputs (all optional; a missing input becomes a "not available" line, never an error):
    steps.tsv, provenance.txt, paths.tsv          run_final.slurm bookkeeping
    tests.csv                                     tests/test_grouped --csv
    bench.csv                                     bench/bench_grouped --csv (full set)
    moe_ffn_fp64.csv, block_sparse_fp64.csv       bench/app
    logs/test_*.log                               suite pass/fail lines, repair counts
    analysis/{nsys,ncu}_summary_*.csv, analysis/roofline_*.csv   scripts/analysis outputs
Speedup definition everywhere: speedup of path P vs base B = time(B) / time(P)  (> 1: P is faster),
taken on the same workload / app config of the same run.
"""
import argparse
import csv
import glob
import math
import os
import re
import statistics
import sys

PATH_ORDER = ["native_loop", "native_grouped", "emu_loop", "emu_loop_batched", "emu_grouped",
              "emu_grouped_reuse", "auto"]
BASE_NG, BASE_ELB = "native_grouped", "emu_loop_batched"
NA = "n/a"


# ---------------------------------------------------------------- helpers
def read_csv(path):
    if not os.path.isfile(path) or os.path.getsize(path) == 0:
        return None
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def read_text(path):
    if not os.path.isfile(path):
        return None
    with open(path, errors="replace") as f:
        return f.read()


def num(s):
    try:
        x = float(s)
    except (TypeError, ValueError):
        return math.nan
    return x


def finite(x):
    return isinstance(x, float) and math.isfinite(x)


def fmt(x, sig=4):
    """Significant-digit formatting of a number read from a CSV (no unit conversion)."""
    if isinstance(x, str):
        return x
    if x is None or not finite(float(x)):
        return NA
    x = float(x)
    if x == 0:
        return "0"
    if abs(x) >= 10 ** sig or abs(x) < 1e-3:
        return f"{x:.{sig - 1}e}"
    return f"{x:.{max(0, sig - 1 - int(math.floor(math.log10(abs(x)))))}f}"


def fmt_ratio(x):
    return f"{x:.2f}x" if finite(x) else NA


def fmt_int(x):
    return str(int(x)) if finite(x) else NA


def div(a, b):
    return a / b if finite(a) and finite(b) and b != 0 else math.nan


def geomean(vals):
    v = [x for x in vals if finite(x) and x > 0]
    return math.exp(sum(math.log(x) for x in v) / len(v)) if v else math.nan


def fmax(vals):
    v = [x for x in vals if finite(x)]
    return max(v) if v else math.nan


def md_table(header, rows, align=None):
    align = align or ("l" + "r" * (len(header) - 1))
    sep = ["---" if a == "l" else "---:" for a in align]
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join(sep) + " |"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def order_paths(paths):
    known = [p for p in PATH_ORDER if p in paths]
    return known + sorted(p for p in paths if p not in PATH_ORDER)


def uniq(seq):
    seen, out = set(), []
    for x in seq:
        if x not in seen:
            seen.add(x)
            out.append(x)
    return out


def src(*names):
    return "Source: " + ", ".join(f"`{n}`" for n in names) + ".\n"


# ---------------------------------------------------------------- 0) header / steps
def sec_header(d):
    out = [f"# Final experiment tables: `{os.path.basename(os.path.normpath(d))}`\n",
           "Generated by `scripts/final/aggregate.py`; every number below is read from the files of this run "
           "directory (or computed from them as stated).\n"]
    prov = read_text(os.path.join(d, "provenance.txt"))
    if prov:
        keep = [ln.strip() for ln in prov.splitlines() if ln.strip()]
        out.append("Provenance (`provenance.txt`):\n\n```\n" + "\n".join(keep) + "\n```\n")
    paths = read_text(os.path.join(d, "paths.tsv"))
    if paths:
        rows = [ln.split("\t") + ["", ""] for ln in paths.splitlines() if ln.strip()]
        out.append("Paths (`paths.tsv`):\n\n" + md_table(["path", "status", "reason"],
                                                          [r[:3] for r in rows], "lll"))
    steps = read_csv_tsv(os.path.join(d, "steps.tsv"))
    if steps:
        cnt = {}
        for r in steps:
            k = "FAIL" if r["status"].startswith("FAIL") else r["status"]
            cnt[k] = cnt.get(k, 0) + 1
        bad = [r for r in steps if r["status"].startswith("FAIL")]
        out.append("Steps (`steps.tsv`): " + ", ".join(f"{v} {k}" for k, v in sorted(cnt.items())) + ".\n")
        if bad:
            out.append(md_table(["failed step", "status", "rc", "log"],
                                [[r["step"], r["status"], r["rc"], r["log"]] for r in bad], "llrl"))
    return "\n".join(out)


def read_csv_tsv(path):
    if not os.path.isfile(path):
        return None
    with open(path, newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


# ---------------------------------------------------------------- 1) correctness
SUITE_PATTERNS = [   # (log name, regex, kind)
    ("test_grouped", re.compile(r"====\s*(\d+)\s+passed,\s*(\d+)\s+failed"), "pf"),
    ("test_graph", re.compile(r"test_graph:\s*(\d+)\s+passed,\s*(\d+)\s+failed"), "pf"),
    ("test_numerics_standalone", re.compile(r"^(PASSED|FAILED)\s*\((\d+)\s+failures\)", re.M), "nf"),
    ("test_i8_grouped", re.compile(r"^(ALL PASS|SOME TESTS FAILED)\s*$", re.M), "flag"),
    ("test_reuse_e2e", None, "rc"),
]


def sec_suites(d):
    steps = {r["step"]: r for r in (read_csv_tsv(os.path.join(d, "steps.tsv")) or [])}
    rows = []
    for name, rx, kind in SUITE_PATTERNS:
        st = steps.get(name)
        log = read_text(os.path.join(d, "logs", name + ".log"))
        if st is None and log is None:
            continue
        passed = failed = NA
        if log and rx is not None:
            ms = list(rx.finditer(log))
            if ms:
                m = ms[-1]
                if kind == "pf":
                    passed, failed = m.group(1), m.group(2)
                elif kind == "nf":
                    failed = m.group(2)
                elif kind == "flag":
                    failed = "0" if m.group(1) == "ALL PASS" else ">=1"
        if log and name == "test_reuse_e2e":
            failed = str(len(re.findall(r"^\s*FAIL\b", log, re.M)))
        rows.append([name, st["status"] if st else NA, st["rc"] if st else NA, passed, failed])
    if not rows:
        return ""
    return ("### Test suites\n\n" + md_table(["suite", "step status", "exit code", "passed", "failed"], rows, "llrrr")
            + src("steps.tsv", "logs/test_*.log") + "\n")


def sec_correctness(d):
    out = ["## 1. Correctness\n", sec_suites(d)]
    t = read_csv(os.path.join(d, "tests.csv"))
    if t:
        rows = []
        for p in order_paths(uniq(r["path"] for r in t)):
            rs = [r for r in t if r["path"] == p]
            rows.append([p, len(rs), sum(r["status"] == "ok" for r in rs), sum(r["status"] != "ok" for r in rs),
                         fmt(fmax(num(r["err_over_gamma"]) for r in rs)),
                         fmt(fmax(num(r["err_vs_native"]) for r in rs)),
                         fmt_int(sum(num(r["nonfinite"]) for r in rs if finite(num(r["nonfinite"])))),
                         fmt_int(sum(num(r["num_fallback"]) for r in rs if finite(num(r["num_fallback"]))))])
        out.append("### test_grouped (test set, all phi, edge cases)\n\n"
                   "worst err/gamma = max over cases of `err_over_gamma` (gate: <= 1); "
                   "worst vs native = max `err_vs_native`.\n\n"
                   + md_table(["path", "cases", "pass", "fail", "worst err/gamma", "worst vs native", "nonfinite",
                               "fallback (sum)"], rows) + src("tests.csv") + "\n")
    else:
        out.append("test_grouped: `tests.csv` not available.\n")
    b = read_csv(os.path.join(d, "bench.csv"))
    if b:
        rows = []
        for p in order_paths(uniq(r["path"] for r in b)):
            rs = [r for r in b if r["path"] == p]
            g = [num(r["err_over_gamma"]) for r in rs]
            rows.append([p, len(rs), sum(r["status"] != "ok" for r in rs), sum(1 for x in g if finite(x) and x > 1),
                         fmt(fmax(g)), fmt(fmax(num(r["err_vs_native"]) for r in rs)),
                         fmt(fmax(num(r["rel_max"]) for r in rs))])
        out.append("### bench_grouped accuracy (full bench set, untimed check call)\n\n"
                   + md_table(["path", "rows", "status != ok", "err/gamma > 1", "worst err/gamma", "worst vs native",
                               "worst rel_max"], rows) + src("bench.csv") + "\n")
    rep = sec_repairs(d)
    if rep:
        out.append(rep)
    return "\n".join(out)


RX_REUSE = re.compile(r"^\s*(\S+)\s+stats:.*?\bfallback=(-?\d+).*?\brepaired=(-?\d+)", re.M)
RX_NUM_ROW = re.compile(r"^\s*(\d+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\d+)\s+(ok|FAIL)\s*$", re.M)
RX_NUM_GROUPED = re.compile(r"total repaired entries=(\d+)")


def sec_repairs(d):
    out = []
    log = read_text(os.path.join(d, "logs", "test_reuse_e2e.log"))
    if log:
        agg = {}
        for m in RX_REUSE.finditer(log):
            tag, rep = m.group(1).lower(), int(m.group(3))
            a = agg.setdefault(tag, [0, 0, 0])   # calls, measured calls, repaired sum
            a[0] += 1
            if rep >= 0:
                a[1] += 1
                a[2] += rep
        if agg:
            rows = [[p, a[0], a[1], a[2] if a[1] else NA] for p, a in
                    sorted(agg.items(), key=lambda kv: (PATH_ORDER.index(kv[0]) if kv[0] in PATH_ORDER else 99, kv[0]))]
            out.append("### Certificate repairs: test_reuse_e2e (GGEMM_STATS_REPAIR=1)\n\n"
                       "repaired = C entries recomputed in FP64 by the certificate (`ggemm_stats_t.num_repaired`, "
                       "-1 = not measured, excluded).\n\n"
                       + md_table(["path", "calls", "measured", "repaired (sum)"], rows)
                       + src("logs/test_reuse_e2e.log") + "\n")
    log = read_text(os.path.join(d, "logs", "test_numerics_standalone.log"))
    if log:
        rs = RX_NUM_ROW.findall(log)
        g = RX_NUM_GROUPED.findall(log)
        if rs or g:
            gates = [num(r[5]) for r in rs]
            rows = [["per-shape x N sweep", len(rs), sum(r[7] == "ok" for r in rs), sum(r[7] == "FAIL" for r in rs),
                     fmt(fmax(gates)), sum(int(r[6]) for r in rs)]]
            if g:
                rows.append(["grouped launch", NA, NA, NA, NA, sum(int(x) for x in g)])
            out.append("### Certificate repairs: test_numerics_standalone\n\n"
                       "gate = max |C-R| / (gamma_n (|alpha||A||B| + |beta||C0|)), must be <= 1; "
                       "rep = entries recomputed in FP64.\n\n"
                       + md_table(["part", "rows", "ok", "FAIL", "worst gate", "repaired (sum)"], rows)
                       + src("logs/test_numerics_standalone.log") + "\n")
    return "\n".join(out)


# ---------------------------------------------------------------- 2/3) bench performance + launches
def bench_view(d, phi):
    b = read_csv(os.path.join(d, "bench.csv"))
    if not b:
        return None
    phis = uniq(r["phi"] for r in b)
    if phi is None:   # most frequent phi of the run
        phi = max(phis, key=lambda p: sum(r["phi"] == p for r in b))
    rows = [r for r in b if num(r["phi"]) == num(phi) and num(r["num_moduli_cfg"]) == 0]
    cell = {}
    for r in rows:
        cell[(r["workload"], r["path"])] = r   # last wins on duplicates
    wls = uniq(r["workload"] for r in rows)
    paths = order_paths(uniq(r["path"] for r in rows))
    return {"cell": cell, "wls": wls, "paths": paths, "phi": phi,
            "family": {r["workload"]: r["family"] for r in rows}, "G": {r["workload"]: r["G"] for r in rows}}


def t_of(v, w, p):
    r = v["cell"].get((w, p))
    if r is None or r["status"] != "ok":
        return math.nan
    return num(r["time_ms"])


def speedup_table(v, base):
    if base not in v["paths"]:
        return f"`{base}` is not in bench.csv for this run -> no speedup table vs {base}.\n"
    others = [p for p in v["paths"] if p != base]
    rows, per_fam = [], {}
    for w in v["wls"]:
        tb = t_of(v, w, base)
        sp = [div(tb, t_of(v, w, p)) for p in others]
        rows.append([w] + [fmt_ratio(x) for x in sp])
        per_fam.setdefault(v["family"][w], []).append(sp)
    for fam, lst in list(per_fam.items()) + [("all", [s for l in per_fam.values() for s in l])]:
        rows.append([f"**geomean {fam}** ({len(lst)})"] + [fmt_ratio(geomean(s[i] for s in lst)) for i in range(len(others))])
    return md_table(["workload"] + [f"{p}" for p in others], rows)


def sec_perf(d, phi):
    v = bench_view(d, phi)
    if v is None:
        return "## 2. Performance (bench_grouped)\n\n`bench.csv` not available.\n"
    out = [f"## 2. Performance (bench_grouped, phi = {v['phi']}, adaptive moduli)\n",
           "time = `time_ms` (median of the timed calls, ms, end-to-end incl. host planning + descriptor H2D). "
           "A cell shows the `status` text if the call did not return ok.\n"]
    rows = []
    for w in v["wls"]:
        r = [w, v["family"][w], v["G"][w]]
        for p in v["paths"]:
            c = v["cell"].get((w, p))
            r.append(NA if c is None else (fmt(num(c["time_ms"])) if c["status"] == "ok" else c["status"]))
        rows.append(r)
    out.append("### 2a. Time (ms)\n\n" + md_table(["workload", "family", "G"] + v["paths"], rows, "llr" + "r" * len(v["paths"]))
               + src("bench.csv") + "\n")
    out.append(f"### 2b. Speedup vs {BASE_NG} = time({BASE_NG}) / time(path)\n\n" + speedup_table(v, BASE_NG)
               + src("bench.csv") + "\n")
    out.append(f"### 2c. Speedup vs {BASE_ELB} = time({BASE_ELB}) / time(path)\n\n" + speedup_table(v, BASE_ELB)
               + src("bench.csv") + "\n")
    return "\n".join(out)


def sec_launches(d, phi):
    v = bench_view(d, phi)
    if v is None:
        return "## 3. Kernel launches\n\n`bench.csv` not available.\n"
    rows = []
    for w in v["wls"]:
        r = [w, v["G"][w]]
        for p in v["paths"]:
            c = v["cell"].get((w, p))
            r.append(fmt_int(num(c["launches"])) if c else NA)
        a = v["cell"].get((w, "auto"))
        r += [fmt_int(num(a["num_fallback"])) if a else NA,
              f"{a['moduli_min']}-{a['moduli_max']}" if a else NA]
        rows.append(r)
    return ("## 3. Kernel launches per call (`launches` = ggemm_stats_t.kernel_launches of the last call)\n\n"
            + md_table(["workload", "G"] + v["paths"] + ["auto fallback", "auto moduli"], rows,
                       "lr" + "r" * len(v["paths"]) + "rr") + src("bench.csv") + "\n")


# ---------------------------------------------------------------- 4) applications
def app_table(rows, key_cols, time_col, extra):
    """rows of one app CSV -> one markdown table (config, path, time, speedups, extra columns)."""
    groups = {}
    for r in rows:
        k = tuple(r[c] for c in key_cols)
        groups.setdefault(k, {})[r["path"]] = r
    out = []
    for k, by_path in groups.items():
        def t(p):
            r = by_path.get(p)
            return num(r[time_col]) if r is not None and r["status"] == "ok" else math.nan
        for p in order_paths(list(by_path)):
            r = by_path[p]
            tp = t(p)
            out.append([" ".join(f"{c}={v}" for c, v in zip(key_cols, k)), p,
                        fmt(num(r[time_col])) if r["status"] == "ok" else r["status"],
                        fmt_ratio(div(t(BASE_NG), tp)), fmt_ratio(div(t(BASE_ELB), tp))]
                       + [f(r) for _, f in extra] + [r["status"]])
    hdr = ["config", "path", time_col + " (ms)", f"x vs {BASE_NG}", f"x vs {BASE_ELB}"] + [h for h, _ in extra] + ["status"]
    return md_table(hdr, out, "ll" + "r" * (len(hdr) - 3) + "l")


def sec_apps(d):
    out = ["## 4. Application end-to-end (bench/app)\n",
           "Speedup columns: time(base) / time(path) within the same config; n/a if the base path did not run.\n"]
    m = read_csv(os.path.join(d, "moe_ffn_fp64.csv"))
    if m:
        out.append("### MoE FFN (FP64)\n\n" + app_table(
            m, ["T", "E", "topk", "d_model", "d_ff", "zipf"], "total_ms_median",
            [("gemm %", lambda r: fmt(num(r["gemm_pct"]), 3)),
             ("launches up+down", lambda r: fmt_int(num(r["launches_up"]) + num(r["launches_down"]))),
             ("fallback up+down", lambda r: fmt_int(num(r["fallback_up"]) + num(r["fallback_down"]))),
             ("err_y / bound", lambda r: fmt(num(r["err_y_over_bound"])))]) + src("moe_ffn_fp64.csv") + "\n")
    else:
        out.append("MoE FFN: `moe_ffn_fp64.csv` not available.\n")
    b = read_csv(os.path.join(d, "block_sparse_fp64.csv"))
    if b:
        out.append("### Block-sparse BSR x dense (FP64)\n\n" + app_table(
            b, ["mode", "atoms", "basis", "nrhs", "G"], "total_ms_median",
            [("gemm ms", lambda r: fmt(num(r["gemm_ms"]))),
             ("launches", lambda r: fmt_int(num(r["launches"]))),
             ("fallback", lambda r: fmt_int(num(r["num_fallback"]))),
             ("err / bound", lambda r: fmt(num(r["err_over_bound"])))]) + src("block_sparse_fp64.csv") + "\n")
    else:
        out.append("Block-sparse: `block_sparse_fp64.csv` not available.\n")
    return "\n".join(out)


# ---------------------------------------------------------------- 5) profiling (scripts/analysis outputs)
STAGES = ["prep", "i8_gemm", "reconstruct", "cublas", "memops", "other"]


def label_of(path, prefix):
    return os.path.splitext(os.path.basename(path))[0][len(prefix):]


def sec_profile(d):
    ana = os.path.join(d, "analysis")
    out = ["## 5. Profiling summary (scripts/analysis outputs)\n"]
    rows = []
    for f in sorted(glob.glob(os.path.join(ana, "nsys_summary_*.csv"))):
        lab = label_of(f, "nsys_summary_")
        for r in read_csv(f) or []:
            span, gap = num(r["span_ns"]), num(r["gap_ns"])
            pct = {s: num(r.get(s + "_pct")) for s in STAGES}
            top = max((s for s in STAGES if finite(pct[s])), key=lambda s: pct[s], default=None)
            rows.append([lab, r["path"], r["calls"], fmt(num(r["kernels"]), 3), fmt(span / 1e3), fmt(num(r["busy_ns"]) / 1e3),
                         fmt(100 * div(gap, span), 3), fmt(num(r["host_ns"]) / 1e3),
                         f"{top} {fmt(pct[top], 3)}%" if top else NA])
    if rows:
        out.append("### nsys: per-call timeline (median over timed calls)\n\n"
                   "us = `*_ns` / 1000; gap % = gap_ns / span_ns.\n\n"
                   + md_table(["workload", "path", "calls", "kernels/call", "GPU span (us)", "GPU busy (us)", "gap %",
                               "host (us)", "top stage"], rows, "ll" + "r" * 6 + "l")
                   + src("analysis/nsys_summary_<workload>.csv") + "\n")
    else:
        out.append("nsys: no `analysis/nsys_summary_*.csv`.\n")
    rows = []
    for f in sorted(glob.glob(os.path.join(ana, "ncu_summary_*.csv"))):
        lab = label_of(f, "ncu_summary_")
        for r in read_csv(f) or []:
            st = f"{r['stall1']} {r.get('stall1_pct')}%" if r.get("stall1") else NA
            rows.append([lab, r["stage"], f"`{r['kernel'][:48]}`", r["launches"], fmt(num(r["duration_us"])),
                         fmt(num(r["imma_pct"]), 3), fmt(num(r["dram_pct"]), 3), fmt(num(r["sm_pct"]), 3),
                         fmt(num(r["occ_pct"]), 3), fmt_int(num(r["regs"])), st])
    if rows:
        out.append("### ncu: kernel metrics (median over launches)\n\n"
                   + md_table(["run", "stage", "kernel", "launches", "duration (us)", "INT8 pipe %", "DRAM %", "SM %",
                               "occupancy %", "regs", "top stall (% share)"], rows, "lll" + "r" * 7 + "l")
                   + src("analysis/ncu_summary_<workload>_<path>.csv") + "\n")
    else:
        out.append("ncu: no `analysis/ncu_summary_*.csv`.\n")
    rows = []
    for f in sorted(glob.glob(os.path.join(ana, "roofline_*.csv"))):
        lab = label_of(f, "roofline_")
        rs = read_csv(f) or []
        for p in order_paths(uniq(r["path"] for r in rs)):
            pr = [r for r in rs if r["path"] == p]
            pct = [num(r["pct_roof"]) for r in pr if finite(num(r["pct_roof"]))]
            bounds = {}
            for r in pr:
                bounds[r["bound"]] = bounds.get(r["bound"], 0) + 1
            rows.append([lab, p, len(pr), fmt(statistics.median(pct), 3) if pct else NA, fmt(fmax(pct), 3),
                         ", ".join(f"{k} {v}" for k, v in sorted(bounds.items()))])
    if rows:
        out.append("### Roofline: % of the path's roof (per path over all workloads)\n\n"
                   + md_table(["label", "path", "points", "median % of roof", "max % of roof", "bound (count)"], rows,
                              "llrrrl")
                   + src("analysis/roofline_<label>.csv") + "\n")
    else:
        out.append("roofline: no `analysis/roofline_*.csv`.\n")
    mds = sorted(os.path.relpath(f, d) for f in glob.glob(os.path.join(ana, "*.md")))
    if mds:
        out.append("Full analysis reports: " + ", ".join(f"`{m}`" for m in mds) + ".\n")
    return "\n".join(out)


# ---------------------------------------------------------------- main
def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("run_dir", help="results/final_<jobid>")
    ap.add_argument("-o", "--out", default=None, help="output markdown (default: <run_dir>/tables.md)")
    ap.add_argument("--phi", default=None, help="phi of the performance tables (default: most frequent in bench.csv)")
    a = ap.parse_args(argv)
    d = a.run_dir
    if not os.path.isdir(d):
        raise SystemExit(f"not a directory: {d}")
    parts = [sec_header(d), sec_correctness(d), sec_perf(d, a.phi), sec_launches(d, a.phi), sec_apps(d), sec_profile(d)]
    md = "\n".join(p.rstrip() + "\n" for p in parts if p)
    out = a.out or os.path.join(d, "tables.md")
    with open(out, "w") as f:
        f.write(md)
    print(f"wrote {out}", file=sys.stderr)
    return md


